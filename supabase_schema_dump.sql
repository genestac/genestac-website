CREATE OR REPLACE FUNCTION "public"."get_audit_logs_with_users"() RETURNS TABLE("id" "uuid", "actor_id" "uuid", "actor_email" "text", "action" "text", "entity_table" "text", "entity_id" "uuid", "old_data" "jsonb", "new_data" "jsonb", "created_at" timestamp with time zone)
    LANGUAGE "plpgsql" SECURITY DEFINER
    AS $$
BEGIN
    -- Check if the calling user is an admin
    IF NOT EXISTS (
        SELECT 1 FROM auth.users 
        WHERE auth.users.id = auth.uid() 
        AND (raw_user_meta_data->>'role' IN ('admin', 'master_admin') OR raw_user_meta_data->>'is_admin' = 'true')
    ) THEN
        RAISE EXCEPTION 'Access Denied: Admins only';
    END IF;

    RETURN QUERY
    SELECT 
        al.id,
        al.actor_id,
        au.email::text AS actor_email,
        al.action,
        al.entity_table,
        al.entity_id,
        al.old_data,
        al.new_data,
        al.created_at
    FROM public.audit_logs al
    LEFT JOIN auth.users au ON au.id = al.actor_id
    ORDER BY al.created_at DESC
    LIMIT 1000;
END;
$$;


ALTER FUNCTION "public"."get_audit_logs_with_users"() OWNER TO "postgres";


CREATE OR REPLACE FUNCTION "public"."handle_audit_log"() RETURNS "trigger"
    LANGUAGE "plpgsql" SECURITY DEFINER
    AS $$
BEGIN
    INSERT INTO public.audit_logs (
        actor_id,
        action,
        entity_table,
        entity_id,
        old_data,
        new_data
    ) VALUES (
        auth.uid(),
        TG_OP,
        TG_TABLE_NAME,
        COALESCE(NEW.id, OLD.id),
        CASE WHEN TG_OP = 'DELETE' THEN row_to_json(OLD)::jsonb
             WHEN TG_OP = 'UPDATE' THEN row_to_json(OLD)::jsonb
             ELSE NULL END,
        CASE WHEN TG_OP = 'DELETE' THEN NULL
             ELSE row_to_json(NEW)::jsonb END
    );
    
    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;
    RETURN NEW;
END;
$$;


ALTER FUNCTION "public"."handle_audit_log"() OWNER TO "postgres";


