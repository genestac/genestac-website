// All valid comparison pairs (for static generation)
export const FOOD_SLUGS = Object.keys(FOODS);

export function parseFoodSlug(slug: string): [FoodNutrition, FoodNutrition] | null {
  // Format: food1-vs-food2-for-weight-loss or food1-vs-food2
  const vsMatch = slug.match(/^(.+)-vs-(.+?)(?:-for-.+)?$/);
  if (!vsMatch) return null;

  const food1Key = vsMatch[1];
  const food2Key = vsMatch[2];

  const food1 = FOODS[food1Key];
  const food2 = FOODS[food2Key];

  if (!food1 || !food2) return null;
  return [food1, food2];
}

// Goal context extracted from slug suffix
export function parseGoalFromSlug(slug: string): string {
  if (slug.includes("-for-weight-loss")) return "weight loss";
  if (slug.includes("-for-diabetes")) return "diabetes management";
  if (slug.includes("-for-muscle")) return "muscle building";
  if (slug.includes("-for-heart")) return "heart health";
  return "general health";
}

// Generate all compare page slugs
export function generateAllCompareSlugs(): string[] {
  const goals = ["weight-loss", "diabetes", "heart-health", "muscle-building"];
  const slugs: string[] = [];

  for (let i = 0; i < FOOD_SLUGS.length; i++) {
    for (let j = 0; j < FOOD_SLUGS.length; j++) {
      if (i === j) continue;
      const base = `${FOOD_SLUGS[i]}-vs-${FOOD_SLUGS[j]}`;
      slugs.push(base);
      goals.forEach((g) => slugs.push(`${base}-for-${g}`));
    }
  }
  return slugs;
}
